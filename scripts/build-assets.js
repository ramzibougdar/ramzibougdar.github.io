#!/usr/bin/env node
/* ==========================================================================
   build-assets.js — CV Ramzi Bougdar (maintenance tool, not a build step)
   Minifies the screen CSS and the site scripts into one file each, which the pages load:
   - css/site.min.css  ← css/tokens.css + css/style.css
   - js/site.min.js    ← data/cv.js, js/i18n.js, js/calc.js, js/icons.js, js/main.js,
                          js/consent.js, js/animations.js (in this order, as one strict script)
   The sources stay the files to edit. Run by scripts/generate-metadata.js before the
   pre-render (check or --write), or on its own:
   - node scripts/build-assets.js           checks the bundles, exits with 1 on any gap
   - node scripts/build-assets.js --write   rewrites them
   Needs Node and npx (esbuild, pinned version, downloaded on first use).
   ========================================================================== */

'use strict';

var fs = require('fs');
var path = require('path');
var childProcess = require('child_process');

var ROOT = path.join(__dirname, '..');
var ESBUILD = 'esbuild@0.24.0';

var BUNDLES = [
  { out: 'css/site.min.css', loader: 'css', files: ['css/tokens.css', 'css/style.css'] },
  {
    out: 'js/site.min.js', loader: 'js',
    files: ['data/cv.js', 'js/i18n.js', 'js/calc.js', 'js/icons.js', 'js/main.js', 'js/consent.js', 'js/animations.js']
  }
];

/**
 * Minifies source code with esbuild (top-level names are kept: the scripts share globals).
 * @param {string} code
 * @param {string} loader "js" or "css"
 * @returns {string}
 */
function minify(code, loader) {
  return childProcess.execFileSync('npx', ['-y', ESBUILD, '--minify', '--loader=' + loader, '--legal-comments=none'], {
    cwd: ROOT, input: code, encoding: 'utf8', stdio: ['pipe', 'pipe', 'inherit'], maxBuffer: 1 << 26
  });
}

/**
 * Builds the expected content of one bundle.
 * @param {Object} bundle
 * @returns {string}
 */
function bundleCode(bundle) {
  var sources = bundle.files.map(function (f) { return fs.readFileSync(path.join(ROOT, f), 'utf8'); });
  // JS: one strict script (main.js already is); ";" keeps the files apart.
  var code = bundle.loader === 'js' ? '"use strict";\n' + sources.join('\n;\n') : sources.join('\n');
  var header = '/* Generated by scripts/build-assets.js from ' + bundle.files.join(', ') + ': do not edit. */\n';
  return header + minify(code, bundle.loader);
}

/**
 * Checks or rewrites every bundle.
 * @param {boolean} write
 * @returns {number} number of out-of-date bundles (0 when writing)
 */
function build(write) {
  var gaps = 0;
  BUNDLES.forEach(function (bundle) {
    var file = path.join(ROOT, bundle.out);
    var expected = bundleCode(bundle);
    var current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === expected) { console.log(bundle.out + ': up to date'); return; }
    if (write) {
      fs.writeFileSync(file, expected);
      console.log(bundle.out + ': ' + (current === null ? 'created' : 'updated'));
    } else {
      gaps++;
      console.error(bundle.out + ': ' + (current === null ? 'missing' : 'out of date') + ' — run: node scripts/generate-metadata.js --write');
    }
  });
  return gaps;
}

module.exports = { build: build };

if (require.main === module) {
  if (build(process.argv.indexOf('--write') !== -1)) process.exit(1);
}
